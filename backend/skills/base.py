from abc import ABC, abstractmethod
from dataclasses import dataclass, field


@dataclass
class SkillConfig:
    id: str
    name: str
    description: str
    icon: str = "book"
    temperature: float = 0.7
    max_history_messages: int = 20
    kb_search_enabled: bool = True
    kb_topic_filter: list[str] | None = None
    kb_include_exercises: bool = False
    enabled_tools: list[str] | None = None  # None = all tools, [] = no tools


